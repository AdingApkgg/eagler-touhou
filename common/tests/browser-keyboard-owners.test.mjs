import assert from 'node:assert/strict';
import {updateKeyboardOwners} from '../browser/keyboard-owners.mjs';
const event = (code, location = 0, repeat = false) => ({code, location, repeat});
const bits = owners => [...owners.values()].reduce((all, owner) => all | owner.bit, 0);
const owners = new Map();
updateKeyboardOwners(owners, event('ShiftLeft', 1), 4, true);
updateKeyboardOwners(owners, event('ShiftRight', 2), 4, true);
updateKeyboardOwners(owners, event('ShiftRight', 0), 4, false);
assert.equal(bits(owners), 4, 'changed-location right release preserves held left Shift');
updateKeyboardOwners(owners, event('Unidentified'), 4, false);
assert.equal(bits(owners), 0, 'unknown-side release retires remaining Shift');
updateKeyboardOwners(owners, event('ShiftLeft'), 4, true);
updateKeyboardOwners(owners, event('ShiftRight'), 4, true);
updateKeyboardOwners(owners, event('Unidentified'), 4, false);
assert.equal(bits(owners), 0, 'ambiguous release must not strand a second modifier owner');
updateKeyboardOwners(owners, event('ArrowUp'), 16, true);
updateKeyboardOwners(owners, event('Numpad8'), 16, true);
updateKeyboardOwners(owners, event('ArrowUp'), 16, false);
assert.equal(bits(owners), 16, 'Arrow and Numpad aliases keep independent ownership');
updateKeyboardOwners(owners, event('Numpad8'), 16, false);
assert.equal(bits(owners), 0);
updateKeyboardOwners(owners, event('Unidentified'), 4, true);
updateKeyboardOwners(owners, event('ShiftLeft', 1), 4, false);
assert.equal(bits(owners), 0, 'UP with better physical identity releases unknown DOWN');
owners.clear();
assert.equal(updateKeyboardOwners(owners, event('ShiftLeft', 1, true), 4, true), false);
assert.equal(bits(owners), 0, 'repeat cannot re-arm cancelled input');
// Host-attested repeat rebuilds ownership cleared by a runtime reset, so a key
// still physically held through the between-stage loading barrier returns.
owners.clear();
assert.equal(updateKeyboardOwners(owners, event('KeyZ', 0, true), 1, true, () => true), true);
assert.equal(bits(owners), 1, 'host-attested repeat rebuilds a cleared owner');
assert.equal(updateKeyboardOwners(owners, event('KeyZ', 0, true), 1, true), true);
assert.equal(bits(owners), 1, 'an established owner keeps reporting repeats');
updateKeyboardOwners(owners, event('KeyZ', 0), 1, false);
assert.equal(bits(owners), 0, 'rebuilt owner still releases on keyup');
// Unattested repeats from synthesized or mapper sources stay cancelled.
owners.clear();
assert.equal(updateKeyboardOwners(owners, event('KeyZ', 0, true), 1, true, () => false), false);
assert.equal(bits(owners), 0, 'repeat without host attestation cannot re-arm');
console.log('PASS shared browser key ownership: aliases, modifier sides, ambiguity, cancellation and repeat rebuild');
